/**
 * What hey-api's output lacks for the protocol's open types (design 5.3.10, SP-4a):
 *
 * - {@link toOpenApi}: hey-api ignores keywords next to a `$ref`, which is how
 *   schemars writes a member of an internally tagged union
 *   (`{$ref: ToolCall, properties: {kind: {const: "tool_call"}}}`), so the tag
 *   would be lost; such a schema becomes `allOf: [{$ref}, {the rest}]`.
 * - Open enums: hey-api writes `"a" | "b" | string`, which TS folds into
 *   `string`; `(string & {})` keeps the known values for completion.
 * - Fallback members of open unions keep the fields this version does not
 *   know: an object gets `.loose()` (`UnknownEvent`); a record such as
 *   `UnknownMember` keeps them already.
 * - `events.gen.ts`: the known event types as literals, and a guard that
 *   narrows an event to them only when its data matches its type.
 *
 * Each rewrite checks that it applied wherever the schema says it should, so
 * a hey-api upgrade that changes its output fails here instead of quietly.
 */

/** A JSON Schema node, as far as this module reads it. */
export interface Node {
  $ref?: string;
  anyOf?: Node[];
  const?: unknown;
  enum?: unknown[];
  properties?: Record<string, Node>;
  type?: string | string[];
  [keyword: string]: unknown;
}

/** `protocol/schema/v1.json`. */
export interface Schema {
  title: string;
  "x-protocol-version": number;
  $defs: Record<string, Node>;
}

/** The first line of every generated file. */
export const HEADER =
  "// Generated by tools/gen-protocol-ts from protocol/schema/v1.json. Do not edit: run `pnpm gen`.";

const DEFS = "#/$defs/";

/** The schema's definitions as the OpenAPI 3.1 document hey-api reads. */
export function toOpenApi(schema: Schema): object {
  return {
    openapi: "3.1.0",
    info: { title: schema.title, version: String(schema["x-protocol-version"]) },
    paths: {},
    components: { schemas: rewrite(schema.$defs) },
  };
}

/** Keywords next to `$ref` that do not constrain the value. */
const annotation = (keyword: string) =>
  ["$ref", "description", "default", "title"].includes(keyword) || keyword.startsWith("x-");

function rewrite(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(rewrite);
  }
  if (typeof value !== "object" || value === null) {
    return value;
  }
  const node = Object.fromEntries(
    Object.entries(value).map(([key, child]) => [
      key,
      key === "$ref" ? String(child).replace(DEFS, "#/components/schemas/") : rewrite(child),
    ]),
  );
  if (!("$ref" in node) || Object.keys(node).every(annotation)) {
    return node;
  }
  const { $ref, description, ...rest } = node;
  return { ...(description === undefined ? {} : { description }), allOf: [{ $ref }, rest] };
}

/** hey-api's `types.gen.ts` and `zod.gen.ts`, and `events.gen.ts`, by file name. */
export function postprocess(
  schema: Schema,
  generated: { types: string; zod: string },
): Record<string, string> {
  const defs = schema.$defs;
  // The client options type of hey-api's SDK; the protocol has no HTTP client.
  let types = replaceOnce(generated.types, /^export type ClientOptions = \{\n[^]*?^\};\n\n/m, "");
  for (const name of openEnums(defs)) {
    const union = new RegExp(`^(export type ${name} = .*) \\| string;$`, "m");
    types = replaceOnce(types, union, "$1 | (string & {});");
  }
  let zod = generated.zod;
  for (const name of fallbacks(defs)) {
    const object = new RegExp(`^(export const z${name} = z\\.object\\([^]*?^\\}\\));$`, "m");
    const record = `export const z${name} = z.record(z.string(), z.unknown());`;
    if (!zod.includes(record)) {
      zod = replaceOnce(zod, object, "$1.loose();");
    }
  }
  return { "types.gen.ts": types, "zod.gen.ts": zod, "events.gen.ts": eventsModule(defs) };
}

/** Replaces the single match of `pattern`; fails on none or several. */
function replaceOnce(text: string, pattern: RegExp, replacement: string): string {
  const matches = text.match(new RegExp(pattern.source, `${pattern.flags}g`)) ?? [];
  if (matches.length !== 1) {
    throw new Error(`expected one match of ${pattern}, found ${matches.length}`);
  }
  return text.replace(pattern, replacement);
}

/** Definitions written by `open_enum!`: the known strings, or any other string. */
function openEnums(defs: Record<string, Node>): string[] {
  return Object.entries(defs)
    .filter(([, def]) => {
      const [known, other, ...more] = def.anyOf ?? [];
      return (
        more.length === 0 &&
        Array.isArray(known?.enum) &&
        known.type === "string" &&
        JSON.stringify(other) === '{"type":"string"}'
      );
    })
    .map(([name]) => name);
}

/** A union member that carries its tag as a `const`. */
const tagged = (member: Node) => Object.values(member.properties ?? {}).some((p) => "const" in p);

/** Definitions that stand for an open union's unknown member: the untagged
 * `$ref` member of an `anyOf` whose other members are tagged. */
function fallbacks(defs: Record<string, Node>): Set<string> {
  const found = new Set<string>();
  const visit = (value: unknown) => {
    if (typeof value !== "object" || value === null) {
      return;
    }
    const members = (value as Node).anyOf;
    if (members?.some(tagged)) {
      for (const member of members) {
        if (!tagged(member) && member.$ref !== undefined) {
          found.add(member.$ref.slice(DEFS.length));
        }
      }
    }
    Object.values(value).forEach(visit);
  };
  visit(defs);
  return found;
}

/** The known event types of `EventBody`, the literal list and the guard. */
function eventsModule(defs: Record<string, Node>): string {
  const events = (defs.EventBody?.anyOf ?? []).flatMap((member) => {
    const type = member.properties?.type?.const;
    const data = member.properties?.data?.$ref;
    return typeof type === "string" && data !== undefined
      ? [{ type: JSON.stringify(type), data: `z${data.slice(DEFS.length)}` }]
      : [];
  });
  if (events.length === 0) {
    throw new Error("EventBody has no known event types");
  }
  const schemas = [...new Set(events.map((e) => e.data))].sort();
  return `${HEADER}

import type * as z from "zod";

import type { Event, EventBody } from "./types.gen";
import { ${schemas.join(", ")} } from "./zod.gen";

/** Every event type this version knows (design 5.3.5). */
export const KNOWN_EVENT_TYPES = [${events.map((e) => e.type).join(", ")}] as const;

export type KnownEventType = (typeof KNOWN_EVENT_TYPES)[number];

/** A body of a known type: narrowing by \`type\` works on it, unlike on \`EventBody\`,
 * whose unknown member has \`type: string\`. */
export type KnownEventBody = Extract<EventBody, { type: KnownEventType }>;

/** An event of a known type, envelope included. */
export type KnownEvent = Extract<Event, { type: KnownEventType }>;

const DATA: Record<KnownEventType, z.ZodType> = {
${events.map((e) => `  ${e.type}: ${e.data},`).join("\n")}
};

export function isKnownEventType(type: string): type is KnownEventType {
  return Object.hasOwn(DATA, type);
}

/**
 * Whether \`event\`, an event or only its body, is of a known type and its data
 * matches that type. A known type with malformed data is not: the client shows
 * it as an unknown event and logs it (ADR-04, revision 4).
 */
export function isKnownEvent<T extends { type: string; data?: unknown }>(
  event: T,
): event is Extract<T, { type: KnownEventType }> {
  return isKnownEventType(event.type) && DATA[event.type].safeParse(event.data).success;
}
`;
}
